export default function PixelFire({ tone = 'classic' }) {
  const ref = useRef(null);

  useEffect(() => {
    const canvas = ref.current;
    const parent = canvas?.parentElement;
    if (!canvas || !parent) return undefined;
    const ctx = canvas.getContext('2d', { alpha: true });
    let width = 0;
    let height = 0;
    let fire = new Uint8Array(0);
    let img = ctx.createImageData(1, 1);
    let timer = 0;
    let visible = true;
    const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const rgb = PALETTES[tone] || PALETTES.classic;

    function resize() {
      const nextW = Math.max(8, Math.floor(parent.clientWidth / PIXEL));
      const nextH = Math.max(8, Math.floor(parent.clientHeight / PIXEL));
      if (nextW === width && nextH === height) return;
      width = nextW;
      height = nextH;
      canvas.width = width;
      canvas.height = height;
      fire = new Uint8Array(width * height);
      const base = (height - 1) * width;
      for (let x = 0; x < width; x += 1) fire[base + x] = FIRE_HOT;
      img = ctx.createImageData(width, height);
    }

    function spread(src) {
      const pixel = fire[src];
      const y = (src / width) | 0;
      if (y === 0) return;
      const x = src - y * width;
      if (pixel === 0) {
        fire[src - width] = 0;
        return;
      }
      const rand = Math.round(Math.random() * 3) & 3;
      let nx = x - rand + 1;
      if (nx < 0) nx = 0;
      else if (nx >= width) nx = width - 1;
      const next = pixel - 1 - (rand & 1);
      fire[(y - 1) * width + nx] = next > 0 ? next : 0;
    }

    function frame() {
      if (!width) return;
      for (let x = 0; x < width; x += 1) {
        for (let y = 1; y < height; y += 1) spread(y * width + x);
      }
      const data = img.data;
      for (let i = 0; i < fire.length; i += 1) {
        const heat = fire[i];
        const index = heat * 3;
        const dst = i * 4;
        data[dst] = rgb[index];
        data[dst + 1] = rgb[index + 1];
        data[dst + 2] = rgb[index + 2];
        data[dst + 3] = heat === 0 ? 0 : 204;
      }
      ctx.putImageData(img, 0, 0);
    }

    function sync() {
      const run = visible && !document.hidden && !reduce;
      if (run && !timer) timer = window.setInterval(frame, 120);
      if (!run && timer) {
        window.clearInterval(timer);
        timer = 0;
      }
    }

    const resizeObserver = new ResizeObserver(resize);
    const viewObserver = new IntersectionObserver(([entry]) => {
      visible = entry.isIntersecting;
      sync();
    });
    resizeObserver.observe(parent);
    viewObserver.observe(parent);
    resize();
    frame();
    sync();
    document.addEventListener('visibilitychange', sync);
    return () => {
      window.clearInterval(timer);
      resizeObserver.disconnect();
      viewObserver.disconnect();
      document.removeEventListener('visibilitychange', sync);
    };
  }, [tone]);

  return (
    <canvas
      ref={ref}
      className="pointer-events-none absolute inset-0 h-full w-full"
      style={{ imageRendering: 'pixelated' }}
      aria-hidden="true"
    />
  );
}
